export function getBlogPostBySlug(slug: string): BlogPost | undefined {
  return blogPosts.find(p => p.slug === slug);
}

export function getAllBlogSlugs(): string[] {
  return blogPosts.map(p => p.slug);
}

/** Новее по дате; при одной дате — больший `id` (последняя добавленная статья) выше. */
function compareBlogPostsByRecency(a: BlogPost, b: BlogPost): number {
  const db = new Date(effectivePublishedIso(b.publishedAt)).getTime()
  const da = new Date(effectivePublishedIso(a.publishedAt)).getTime()
  if (db !== da) return db - da
  return Number(b.id) - Number(a.id)
}

export function getRecentPosts(count: number = 3): BlogPost[] {
  return [...blogPosts].sort(compareBlogPostsByRecency).slice(0, count);
}

/** Все статьи блога, от новых к старым (для списка /blog). */
export function getAllBlogPostsSorted(): BlogPost[] {
  return [...blogPosts].sort(compareBlogPostsByRecency);
}

/** Id самых свежих статей (по умолчанию две последние) — для бейджа «New». */
export function getNewBlogPostIdSet(count: number = 2): Set<string> {
  return new Set(
    [...blogPosts].sort(compareBlogPostsByRecency).slice(0, count).map((p) => p.id)
  )
}

